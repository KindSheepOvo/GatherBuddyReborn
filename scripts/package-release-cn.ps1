$ErrorActionPreference = 'Stop'
$version = $env:PLUGIN_VERSION
if ($version -notmatch '^\d+\.\d+\.\d+\.\d+$') { throw 'Missing or invalid plugin release version.' }
$name = 'GatherBuddyReborn'
$dll = Get-Item -LiteralPath "build/$name.dll"
if ($dll.Length -eq 0 -or [Reflection.AssemblyName]::GetAssemblyName($dll.FullName).Version.ToString() -ne $version) {
    throw 'Plugin DLL is empty or its assembly version differs from the release.'
}
$cli = Get-Item -LiteralPath 'build/raphael-cli.exe'
if ($cli.Length -eq 0) { throw 'Raphael companion executable is empty.' }
# Keep the plugin assets/dependencies copied by MSBuild but do not distribute build symbols
# or a nested ZIP generated by a plugin packaging target.
Get-ChildItem -LiteralPath build -File | Where-Object Extension -In '.pdb', '.zip' | Remove-Item
$manifest = Get-Content -Raw -LiteralPath "GatherBuddy/$name.json" | ConvertFrom-Json -AsHashtable
if ($manifest.InternalName -cne $name -or $manifest.DalamudApiLevel -ne 15 -or $manifest.TestingDalamudApiLevel -ne 15) {
    throw 'Unexpected plugin family or API level; review both release and feed support.'
}
$manifest.RepoUrl = 'https://github.com/LienChan666/GatherBuddyReborn'
$manifest.AssemblyVersion = $version
$manifest.TestingAssemblyVersion = $version
$manifest | ConvertTo-Json -Depth 20 | Set-Content -Encoding utf8NoBOM -LiteralPath "build/$name.json"
New-Item -ItemType Directory -Path publish | Out-Null
Copy-Item -LiteralPath "build/$name.json" -Destination "publish/$name.json"
$package = "publish/$name-$version.zip"
Compress-Archive -Path 'build/*' -DestinationPath $package
$zip = [IO.Compression.ZipFile]::OpenRead((Resolve-Path -LiteralPath $package).Path)
try {
    foreach ($required in "$name.dll", "$name.json", 'raphael-cli.exe', 'LICENSE.raphael-rs.txt', 'LICENSE.GatherBuddyReborn.txt') {
        $entry = $zip.GetEntry($required)
        if ($null -eq $entry -or $entry.Length -eq 0) { throw "Missing root file in the release ZIP: $required" }
    }
} finally {
    $zip.Dispose()
}
Get-FileHash -Algorithm SHA256 -LiteralPath $package,"publish/$name.json"
